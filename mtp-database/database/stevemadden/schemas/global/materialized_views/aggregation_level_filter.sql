create MATERIALIZED VIEW if not exists "global".aggregation_level_filter
   
AS SELECT 
    grouped_data.l4_name AS aggregation_code,
    grouped_data.product_code AS products,
    grouped_data.article,
    grouped_data.color_id,
    grouped_data.style_name,
    grouped_data.color_name,
    grouped_data.fullprice_unit_retail,
    grouped_data.fullprice_clearance_flag,
    grouped_data.outletprice_unit_retail,
    grouped_data.outletprice_clearance_flag,
    grouped_data.otherprice1_unit_retail,
    grouped_data.otherprice1_clearance_flag,
    grouped_data.otherprice2_unit_retail,
    grouped_data.otherprice2_clearance_flag,
    grouped_data.size,
    grouped_data.launch_date,
    grouped_data.season_code,
    grouped_data.attribute1_desc,
    grouped_data.parent_id,
    grouped_data.l0_name,
    grouped_data.l1_name,
    grouped_data.l2_name,
    grouped_data.l3_name,
    grouped_data.l4_name
FROM (
    SELECT 
        array_agg(pa.product_code) AS product_code,
        max(pa.article::text) AS article,
        max(pa.color_id::text) AS color_id,
        max(pa.style_name::text) AS style_name,
        max(pa.color_name::text) AS color_name,
        max(pa.fullprice_unit_retail) AS fullprice_unit_retail,
        max(pa.fullprice_clearance_flag) AS fullprice_clearance_flag,
        max(pa.outletprice_unit_retail) AS outletprice_unit_retail,
        max(pa.outletprice_clearance_flag) AS outletprice_clearance_flag,
        max(pa.otherprice1_unit_retail) AS otherprice1_unit_retail,
        max(pa.otherprice1_clearance_flag) AS otherprice1_clearance_flag,
        max(pa.otherprice2_unit_retail) AS otherprice2_unit_retail,
        max(pa.otherprice2_clearance_flag) AS otherprice2_clearance_flag,
        max(pa.size::text) AS size,
        max(pa.launch_date) AS launch_date,
        max(pa.season_code::text) AS season_code,
        max(pa.attribute1_desc::text) AS attribute1_desc,
        max(pa.parent_id::text) AS parent_id,
        pa.l0_name,
        pa.l1_name,
        pa.l2_name,
        pa.l3_name,
        pa.l4_name
    FROM global.product_attributes_filter pa
    WHERE pa.is_deleted IS FALSE
    GROUP BY pa.l4_name, pa.l0_name, pa.l1_name, pa.l2_name, pa.l3_name
) grouped_data
WITH DATA;


